#!/usr/bin/env python3
"""Generate a compact 1-bpp bitmap table for all precomposed Hangul syllables.

The generated header is a build artifact. It is created in CI from NanumGothic,
which is distributed under the SIL Open Font License 1.1.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FIRST = 0xAC00
LAST = 0xD7A3
FONT_PATH = "/usr/share/fonts/truetype/nanum/NanumGothic.ttf"
OUT = Path("gx/gui/hangul_font_data.h")

SCALE = 2
font = ImageFont.truetype(FONT_PATH, 16 * SCALE)
rows = []
for codepoint in range(FIRST, LAST + 1):
    image = Image.new("L", (16 * SCALE, 16 * SCALE), 0)
    draw = ImageDraw.Draw(image)
    # A 1-pixel white stroke thickens the 1-bpp glyphs for better readability on Wii.
    draw.text((8 * SCALE, 8 * SCALE), chr(codepoint), font=font, fill=255, anchor="mm", stroke_width=1, stroke_fill=255)
    image = image.resize((16, 16), Image.Resampling.LANCZOS)
    pixels = image.load()
    packed = []
    for y in range(16):
        for byte_x in range(2):
            value = 0
            for bit in range(8):
                if pixels[byte_x * 8 + bit, y] >= 112:
                    value |= 0x80 >> bit
            packed.append(value)
    rows.append("  { " + ", ".join(f"0x{value:02X}" for value in packed) + " },")

OUT.write_text(
    "/* Generated by tools/gen_hangul_font.py; do not edit by hand. */\n"
    "/* Source font: NanumGothic, SIL Open Font License 1.1. */\n"
    "#ifndef HANGUL_FONT_DATA_H\n"
    "#define HANGUL_FONT_DATA_H\n"
    "#define HANGUL_GLYPH_FIRST 0xAC00u\n"
    "#define HANGUL_GLYPH_COUNT 11172u\n"
    "static const unsigned char hangul_font_1bpp[HANGUL_GLYPH_COUNT][32] = {\n"
    + "\n".join(rows)
    + "\n};\n#endif\n",
    encoding="ascii",
)
print(f"Generated {OUT} ({OUT.stat().st_size} bytes)")
